function [E, H] = spheroid_eval(sol, X, Y, Z, field, side)
%SPHEROID_EVAL Evaluate a solved homogeneous-spheroid field.

narginchk(4, 6);
if nargin < 5 || isempty(field)
    field = 'total';
end
if nargin < 6 || isempty(side)
    side = 'auto';
end
field = checked_choice(field, {'total', 'scattered', 'incident'}, 'field');
side = checked_choice(side, {'auto', 'in', 'out'}, 'side');
validate_solution(sol);
validateattributes(X, {'numeric'}, {'real', 'finite'}, mfilename, 'X');
validateattributes(Y, {'numeric'}, {'real', 'finite'}, mfilename, 'Y');
validateattributes(Z, {'numeric'}, {'real', 'finite'}, mfilename, 'Z');
if ~isequal(size(X), size(Y), size(Z))
    error('spheroid_eval:InputSizeMismatch', ...
        'X, Y, and Z must have equal sizes.');
end

X = X(:);
Y = Y(:);
Z = Z(:);
if strcmp(side, 'auto')
    level = (X/sol.b).^2 + (Y/sol.b).^2 + (Z/sol.a).^2;
    outside = level >= 1 - 64*eps;
else
    g = sph_coords(sol.type, X/sol.semifocal, Y/sol.semifocal, ...
        Z/sol.semifocal);
    if any(abs(g.xi - sol.xi0) > 1e-8)
        error('spheroid_eval:InvalidForcedSide', ...
            'Forced side is allowed only within 1e-8 in xi of the boundary.');
    end
    outside = repmat(strcmp(side, 'out'), numel(X), 1);
end

[Einc, Hinc] = incident_plane_wave(sol.km, sol.n_m, sol.theta_inc, ...
    sol.phi_inc, sol.pol, X, Y, Z);
if strcmp(field, 'incident')
    E = Einc;
    H = Hinc;
    return
end

Ephysical = complex(zeros(numel(X), 3));
Hphysical = complex(zeros(numel(X), 3));
scattered_output = strcmp(field, 'scattered');
chunk_size = 2000;
for first = 1:chunk_size:numel(X)
    last = min(numel(X), first + chunk_size - 1);
    chunk = first:last;
    out_chunk = outside(chunk);
    if any(out_chunk)
        index = chunk(out_chunk);
        gout = sph_coords(sol.type, X(index)/sol.semifocal, ...
            Y(index)/sol.semifocal, Z(index)/sol.semifocal);
        [Escattered, Hscattered] = evaluate_region(sol, gout, true);
        if scattered_output
            Ephysical(index, :) = Escattered;
            Hphysical(index, :) = Hscattered;
        else
            Ephysical(index, :) = Einc(index, :) + Escattered;
            Hphysical(index, :) = Hinc(index, :) + Hscattered;
        end
    end
    if any(~out_chunk)
        index = chunk(~out_chunk);
        gin = sph_coords(sol.type, X(index)/sol.semifocal, ...
            Y(index)/sol.semifocal, Z(index)/sol.semifocal);
        [Einternal, Hinternal] = evaluate_region(sol, gin, false);
        if scattered_output
            Ephysical(index, :) = Einternal - Einc(index, :);
            Hphysical(index, :) = Hinternal - Hinc(index, :);
        else
            Ephysical(index, :) = Einternal;
            Hphysical(index, :) = Hinternal;
        end
    end
end

E = Ephysical;
H = Hphysical;
values = [E(:); H(:)];
if any(~isfinite(real(values))) || any(~isfinite(imag(values)))
    error('spheroid_eval:NonfiniteOutput', ...
        'Field evaluation produced a nonfinite value.');
end
end

function [E, H] = evaluate_region(sol, g, exterior)
points = numel(g.xi);
Eeta = complex(zeros(1, points));
Exi = complex(zeros(1, points));
Ephi = complex(zeros(1, points));
Heta = complex(zeros(1, points));
Hxi = complex(zeros(1, points));
Hphi = complex(zeros(1, points));
for mu = 0:sol.M
    data = sol.mu_data{mu + 1};
    if isempty(data)
        continue
    end
    if exterior
        W = sph_angular(data.eg_ext, g);
        V = sph_radial_ode_eval(data.rod_ext, g);
        c = sol.c_ext;
        refractive_index = sol.n_m;
    else
        W = sph_angular(data.eg_int, g);
        [V, radial_ok] = sph_radial(data.eg_int, 1, g, sol.c_int);
        if ~radial_ok
            error('spheroid_eval:RadialFailure', ...
                'The internal radial series failed its finite/tail check.');
        end
        c = sol.c_int;
        refractive_index = sol.n_p;
    end
    mode_indices = find(abs([sol.modes.m]) == mu);
    for k = mode_indices
        mode = sol.modes(k);
        if exterior
            first_coefficient = mode.a(:).';
            second_coefficient = mode.b(:).';
        else
            first_coefficient = mode.c(:).';
            second_coefficient = mode.d(:).';
        end
        [Mwave, Nwave] = sph_vecwave(W, V, g, mode.m, c);
        phase = exp(1i*mode.m*g.phi(:).');
        Eeta = Eeta + phase .* (first_coefficient*Nwave.eta + ...
            second_coefficient*Mwave.eta);
        Exi = Exi + phase .* (first_coefficient*Nwave.xi + ...
            second_coefficient*Mwave.xi);
        Ephi = Ephi + phase .* (first_coefficient*Nwave.phi + ...
            second_coefficient*Mwave.phi);
        Heta = Heta - 1i*refractive_index*phase .* ...
            (first_coefficient*Mwave.eta + second_coefficient*Nwave.eta);
        Hxi = Hxi - 1i*refractive_index*phase .* ...
            (first_coefficient*Mwave.xi + second_coefficient*Nwave.xi);
        Hphi = Hphi - 1i*refractive_index*phase .* ...
            (first_coefficient*Mwave.phi + second_coefficient*Nwave.phi);
    end
end
E = to_cartesian(Eeta, Exi, Ephi, g);
H = to_cartesian(Heta, Hxi, Hphi, g);
end

function value = to_cartesian(eta_component, xi_component, phi_component, g)
value = eta_component(:).*g.e_eta + xi_component(:).*g.e_xi + ...
    phi_component(:).*g.e_phi;
end

function validate_solution(sol)
required = {'route', 'type', 'a', 'b', 'semifocal', 'xi0', 'c_ext', 'c_int', ...
    'km', 'n_m', 'n_p', 'theta_inc', 'phi_inc', 'pol', 'L', 'M', ...
    'modes', 'mu_data'};
if ~isstruct(sol) || ~isscalar(sol) || ~all(isfield(sol, required)) || ...
        ~strcmp(sol.route, 'spheroid')
    error('spheroid_eval:InvalidSolution', ...
        'sol must be a spheroid solution returned by spheroid_solve.');
end
if ~(strcmp(sol.type, 'prolate') || strcmp(sol.type, 'oblate')) || ...
        ~(isnumeric(sol.semifocal) && isscalar(sol.semifocal) && ...
        isreal(sol.semifocal) && isfinite(sol.semifocal) && ...
        sol.semifocal > 0) || ...
        ~(isnumeric(sol.a) && isscalar(sol.a) && isreal(sol.a) && ...
        isfinite(sol.a) && sol.a > 0) || ...
        ~(isnumeric(sol.b) && isscalar(sol.b) && isreal(sol.b) && ...
        isfinite(sol.b) && sol.b > 0) || ...
        ~(isnumeric(sol.L) && isscalar(sol.L) && isreal(sol.L) && ...
        isfinite(sol.L) && sol.L == fix(sol.L) && sol.L >= 0) || ...
        ~(isnumeric(sol.M) && isscalar(sol.M) && isreal(sol.M) && ...
        isfinite(sol.M) && sol.M == fix(sol.M) && sol.M >= 0 && ...
        sol.M <= sol.L) || ~iscell(sol.mu_data) || ...
        numel(sol.mu_data) ~= sol.M + 1 || ...
        numel(sol.modes) ~= 2*sol.M + 1
    error('spheroid_eval:InvalidSolution', ...
        'The spheroid solution structure is inconsistent.');
end
mode_fields = {'m', 'mu', 'a', 'b', 'c', 'd', 'analytically_zeroed'};
if ~isstruct(sol.modes) || ~all(isfield(sol.modes, mode_fields)) || ...
        ~isequal(sort([sol.modes.m]), -sol.M:sol.M) || ...
        any([sol.modes.mu] ~= abs([sol.modes.m])) || ...
        ~all(arrayfun(@(mode) islogical(mode.analytically_zeroed) && ...
        isscalar(mode.analytically_zeroed), sol.modes))
    error('spheroid_eval:InvalidSolution', ...
        'The spheroid solution structure is inconsistent.');
end
for mu = 0:sol.M
    data = sol.mu_data{mu + 1};
    modes = sol.modes(abs([sol.modes.m]) == mu);
    expected_count = sol.L - mu + 1;
    coefficients = {modes.a, modes.b, modes.c, modes.d};
    valid_coefficients = all(cellfun(@(value) isnumeric(value) && ...
        isvector(value) && numel(value) == expected_count && ...
        all(isfinite(value(:))), coefficients));
    if ~valid_coefficients
        error('spheroid_eval:InvalidSolution', ...
            'Every modal coefficient vector must match its angular sector.');
    end
    if isempty(data)
        zero_coefficients = all(cellfun(@(value) ...
            all(value(:) == 0), coefficients));
        if ~all([modes.analytically_zeroed]) || ~zero_coefficients
            error('spheroid_eval:InvalidSolution', ...
                'An omitted angular sector must have zero coefficients.');
        end
    elseif ~valid_sector_data(data, sol, mu)
        error('spheroid_eval:InvalidSolution', ...
            'Angular-sector data are inconsistent with their index.');
    end
end
end

function valid = valid_sector_data(data, sol, mu)
required = {'mu', 'eg_ext', 'eg_int', 'rod_ext'};
valid = isstruct(data) && isscalar(data) && all(isfield(data, required)) && ...
    isequal(data.mu, mu) && ...
    valid_eigen_data(data.eg_ext, sol.type, mu, sol.c_ext, sol.L) && ...
    valid_eigen_data(data.eg_int, sol.type, mu, sol.c_int, sol.L);
if ~valid
    return
end
rod = data.rod_ext;
required = {'type', 'mu', 'lambda', 'c', 'xi0', 'xi_start', ...
    'arbitrary_scale', 'normalization_xi', 'solution', 'qtilde_xi0', ...
    'asymptotic_coefficients', 'asymptotic_stop', ...
    'asymptotic_argument_scale', 'asymptotic_U_start', 'l'};
valid = isstruct(rod) && isscalar(rod) && all(isfield(rod, required)) && ...
    strcmp(rod.type, sol.type) && isequal(rod.mu, mu) && ...
    isequal(rod.c, sol.c_ext) && isequal(rod.xi0, sol.xi0) && ...
    isequal(rod.arbitrary_scale, true) && ...
    isequal(rod.normalization_xi, rod.xi0) && ...
    isequal(rod.l, data.eg_ext.l) && ...
    isequal(rod.lambda, data.eg_ext.lambda);
if ~valid
    return
end
solution = rod.solution;
solution_fields = {'solver', 'extdata', 'x', 'y', 'stats', 'idata'};
mode_count = sol.L - mu + 1;
valid = isnumeric(rod.xi_start) && isscalar(rod.xi_start) && ...
    isreal(rod.xi_start) && isfinite(rod.xi_start) && ...
    rod.xi_start >= rod.xi0 && ...
    isnumeric(rod.qtilde_xi0) && ...
    numel(rod.qtilde_xi0) == mode_count && ...
    isnumeric(rod.asymptotic_coefficients) && ...
    size(rod.asymptotic_coefficients, 2) == mode_count && ...
    isnumeric(rod.asymptotic_stop) && isreal(rod.asymptotic_stop) && ...
    numel(rod.asymptotic_stop) == mode_count && ...
    isnumeric(rod.asymptotic_argument_scale) && ...
    isscalar(rod.asymptotic_argument_scale) && ...
    isreal(rod.asymptotic_argument_scale) && ...
    isfinite(rod.asymptotic_argument_scale) && ...
    rod.asymptotic_argument_scale > 0 && ...
    isnumeric(rod.asymptotic_U_start) && ...
    numel(rod.asymptotic_U_start) == mode_count && ...
    isstruct(solution) && isscalar(solution) && ...
    all(isfield(solution, solution_fields));
if ~valid
    return
end
stored_values = [rod.qtilde_xi0(:); ...
    rod.asymptotic_coefficients(:); rod.asymptotic_U_start(:)];
stop = rod.asymptotic_stop(:);
valid = ischar(solution.solver) && isrow(solution.solver) && ...
    strcmp(solution.solver, 'ode113') && ...
    isstruct(solution.extdata) && isscalar(solution.extdata) && ...
    isstruct(solution.stats) && isscalar(solution.stats) && ...
    isstruct(solution.idata) && isscalar(solution.idata) && ...
    isnumeric(solution.x) && isreal(solution.x) && ...
    isvector(solution.x) && numel(solution.x) >= 2 && ...
    all(isfinite(solution.x(:))) && isnumeric(solution.y) && ...
    isequal(size(solution.y), [2*mode_count, numel(solution.x)]) && ...
    all(isfinite(real(solution.y(:)))) && ...
    all(isfinite(imag(solution.y(:)))) && ...
    all(isfinite(real(stored_values))) && ...
    all(isfinite(imag(stored_values))) && all(isfinite(stop)) && ...
    all(stop >= 1) && all(stop == fix(stop)) && ...
    all(stop <= size(rod.asymptotic_coefficients, 1));
end

function valid = valid_eigen_data(eg, type, mu, c, L)
required = {'type', 'mu', 'c', 'L', 'l', 'lambda', 'd', 'rmax'};
valid = isstruct(eg) && isscalar(eg) && all(isfield(eg, required));
if ~valid
    return
end
count = L - mu + 1;
valid = strcmp(eg.type, type) && isequal(eg.mu, mu) && ...
    isequal(eg.c, c) && isequal(eg.L, L) && ...
    isequal(eg.l, (mu:L).') && isnumeric(eg.lambda) && ...
    isequal(size(eg.lambda), [count, 1]) && ...
    all(isfinite(real(eg.lambda))) && all(isfinite(imag(eg.lambda))) && ...
    isnumeric(eg.rmax) && isscalar(eg.rmax) && isreal(eg.rmax) && ...
    isfinite(eg.rmax) && eg.rmax >= 0 && eg.rmax == fix(eg.rmax) && ...
    isnumeric(eg.d) && isequal(size(eg.d), [eg.rmax + 1, count]) && ...
    all(isfinite(real(eg.d(:)))) && all(isfinite(imag(eg.d(:))));
end

function value = checked_choice(value, choices, name)
if isstring(value) && isscalar(value)
    value = char(value);
end
if ~(ischar(value) && isrow(value) && ismember(value, choices))
    error('spheroid_eval:InvalidOption', ...
        '%s must be one of: %s.', name, strjoin(choices, ', '));
end
end
